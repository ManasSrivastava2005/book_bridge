import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('./src/utils/reader.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const exports={};
new Function('exports',compiled)(exports);
const {parseReaderState,readerKey,readerUrl,validReaderPage}=exports;
assert.notEqual(readerKey(1,'4'),readerKey(2,'4'));
assert.notEqual(readerKey(1,'4'),readerKey(1,'5'));
assert.throws(()=>parseReaderState('broken'));
assert.throws(()=>parseReaderState('{"page":0,"bookmarks":[]}'));
assert.deepEqual(parseReaderState(null),{page:1,bookmarks:[]});
assert.deepEqual(parseReaderState(JSON.stringify({page:3,bookmarks:[{page:3,note:'Hello'},{page:3,note:'Duplicate'},{page:-1,note:'Bad'},{page:2,note:'Earlier'}]})),{page:3,bookmarks:[{page:2,note:'Earlier'},{page:3,note:'Hello'}]});
assert.equal(readerUrl('/uploads/doc.pdf','http://localhost:8000'),'http://localhost:8000/uploads/doc.pdf');
assert.equal(readerUrl('javascript:alert(1)','http://localhost:8000'),null);
assert.equal(readerUrl('data:text/html,hello','http://localhost:8000'),null);
assert.equal(readerUrl('', 'http://localhost:8000'),null);
assert.equal(validReaderPage(1.5),false);
assert.equal(validReaderPage(0),false);
assert.equal(validReaderPage(NaN),false);
assert.equal(validReaderPage(100001),false);
console.log('Reader storage, account/document separation, URL and navigation checks passed.');
