from datetime import datetime

from pydantic import BaseModel, Field, model_validator, field_validator


class BookCreate(BaseModel):
    """
    Schema for CREATING a new book (what the user sends in the request body).

    Notice: no 'id' or 'created_at' here — the database generates those
    automatically. We only ask for what the user should provide.
    """

    title: str = Field(min_length=1, max_length=255)
    author: str = Field(min_length=1, max_length=255)
    isbn: str | None = Field(default=None, max_length=13)
    category: str | None = Field(default=None, max_length=100)
    rack: str | None = Field(default=None, max_length=50)
    shelf: str | None = Field(default=None, max_length=50)
    description: str | None = None
    cover_image: str | None = Field(default=None, max_length=500)
    publication_year: int | None = Field(default=None, ge=1000, le=2100)
    library_id: int | None = Field(default=None, gt=0)
    total_copies: int = Field(default=1, ge=1)
    available_copies: int | None = Field(default=None, ge=0)

    @field_validator('title', 'author')
    @classmethod
    def nonblank(cls, value):
        if value is not None and not value.strip(): raise ValueError('Must not be blank')
        return value.strip() if value is not None else value

    @field_validator('cover_image')
    @classmethod
    def safe_cover(cls, value):
        if value and not (value.startswith(('https://', 'http://')) or (value.startswith('/uploads/') and '..' not in value)):
            raise ValueError('Use an HTTP(S) cover URL or an uploaded image path')
        return value or None

    @model_validator(mode="after")
    def validate_inventory(self):
        if self.available_copies is None:
            self.available_copies = self.total_copies
        elif self.available_copies > self.total_copies:
            raise ValueError("available_copies cannot be greater than total_copies")
        return self


class BookUpdate(BaseModel):
    """
    Schema for UPDATING a book.

    All fields are optional (None by default) because the user might
    only want to update the title without changing the author, etc.
    """

    title: str | None = Field(default=None, min_length=1, max_length=255)
    author: str | None = Field(default=None, min_length=1, max_length=255)
    isbn: str | None = Field(default=None, max_length=13)
    category: str | None = Field(default=None, max_length=100)
    rack: str | None = Field(default=None, max_length=50)
    shelf: str | None = Field(default=None, max_length=50)
    description: str | None = None
    cover_image: str | None = Field(default=None, max_length=500)
    publication_year: int | None = Field(default=None, ge=1000, le=2100)
    library_id: int | None = Field(default=None, gt=0)
    total_copies: int | None = Field(default=None, ge=1)
    available_copies: int | None = Field(default=None, ge=0)

    @field_validator('title', 'author')
    @classmethod
    def nonblank(cls, value):
        if value is not None and not value.strip(): raise ValueError('Must not be blank')
        return value.strip() if value is not None else value

    @field_validator('cover_image')
    @classmethod
    def safe_cover(cls, value):
        if value and not (value.startswith(('https://', 'http://')) or (value.startswith('/uploads/') and '..' not in value)):
            raise ValueError('Use an HTTP(S) cover URL or an uploaded image path')
        return value or None

    @model_validator(mode="after")
    def validate_inventory(self):
        for field in ('title', 'author', 'total_copies', 'available_copies'):
            if field in self.model_fields_set and getattr(self, field) is None:
                raise ValueError(f'{field} cannot be null')
        if (
            self.total_copies is not None
            and self.available_copies is not None
            and self.available_copies > self.total_copies
        ):
            raise ValueError("available_copies cannot be greater than total_copies")
        return self


class BookResponse(BaseModel):
    """
    Schema for the RESPONSE (what we send back to the user).

    Includes all fields, including 'id' and 'created_at' which are
    generated by the database.

    'model_config' with 'from_attributes=True' tells Pydantic:
    "Hey, the data I'm receiving is a SQLAlchemy model object, not a dict.
     Read the values from its attributes."
    """

    id: int
    title: str
    author: str
    isbn: str | None = None
    category: str | None = None
    rack: str | None = None
    shelf: str | None = None
    description: str | None = None
    cover_image: str | None = None
    publication_year: int | None = None
    library_id: int | None = None
    total_copies: int
    available_copies: int
    created_at: datetime

    model_config = {"from_attributes": True}
